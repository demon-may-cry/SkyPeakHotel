package com.skypeak.hotel.entity.enums;

/**
 * Статусы учетной записи пользователя в системе отеля.
 *
 * <p>Определяет состояние аккаунта и доступные действия:</p>
 *
 * <ul>
 *   <li>{@link #ACTIVE} - активный пользователь, может авторизоваться, бронировать номера и совершать транзакции</li>
 *   <li>{@link #INACTIVE} - неактивный аккаунт, запрещена авторизация, активация возможна пользователем или администратором</li>
 *   <li>{@link #BLOCKED} - заблокированный аккаунт администратором за нарушения, требуется ручная разблокировка</li>
 * </ul>
 *
 * @author Дмитрий Ельцов
 * @see com.skypeak.hotel.entity.UserEntity
 */
public enum Status {
    /** Активный пользователь - полная функциональность доступна */
    ACTIVE,
    /** Неактивный аккаунт - требуется активация, авторизация запрещена */
    INACTIVE,
    /** Заблокирован администратором - полное ограничение доступа до разблокировки */
    BLOCKED
}
